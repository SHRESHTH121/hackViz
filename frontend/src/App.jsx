import { useCallback, useMemo, useState } from 'react'
import { Activity, BellRing, LayoutDashboard, MonitorCheck, ShieldHalf, UserPlus } from 'lucide-react'
import { api } from './services/api'
import { usePolling } from './hooks/usePolling'
import { navigate, useHashRoute } from './hooks/useHashRoute'
import { AppContext } from './components/ui'
import EventModal from './components/EventModal'
import AddEmployeeModal from './components/AddEmployeeModal'
import Dashboard from './pages/Dashboard'
import EmployeeProfile from './pages/EmployeeProfile'
import LiveFeed from './pages/LiveFeed'
import Alerts from './pages/Alerts'
import Monitoring from './pages/Monitoring'

const NAV = [
  { key: 'dashboard', label: 'Dashboard', icon: LayoutDashboard, to: '#/' },
  { key: 'activity', label: 'Live Activity', icon: Activity, to: '#/activity' },
  { key: 'alerts', label: 'Anomaly Alerts', icon: BellRing, to: '#/alerts' },
  { key: 'monitoring', label: 'Monitoring Status', icon: MonitorCheck, to: '#/monitoring' },
]
const TITLES = { dashboard: 'Security Overview', employees: 'Employee Profile', activity: 'Live Activity Feed', alerts: 'Anomaly Alerts', monitoring: 'Monitoring Status' }

function Pill({ label, state, title }) {
  return <span className="status-pill" title={title}><span className={`dot ${state}`} />{label}</span>
}

export default function App() {
  const route = useHashRoute()
  const [eventId, setEventId] = useState(null)
  const [adding, setAdding] = useState(false)
  const [toastMsg, setToastMsg] = useState(null)
  const [version, setVersion] = useState(0)
  const status = usePolling(() => api.status(), 5000)
  const alertCount = usePolling(() => api.anomalies({ only_anomalies: true, limit: 500 }).then((r) => r.length), 5000)

  const toast = useCallback((msg, kind = 'info') => {
    setToastMsg({ msg, kind })
    clearTimeout(window.__hvToast)
    window.__hvToast = setTimeout(() => setToastMsg(null), 4500)
  }, [])
  const ctx = useMemo(() => ({
    openEvent: setEventId, toast, refreshAll: () => setVersion((v) => v + 1), version,
    openAddEmployee: () => setAdding(true), status: status.data,
  }), [toast, version, status.data])

  const s = status.data
  const backendOk = !status.error
  const dbOk = backendOk && s?.database?.ok
  const ollamaState = !backendOk || !s ? 'idle' : s?.ollama?.ok ? (s.ollama.model_available ? 'ok' : 'warn') : 'bad'
  const mon = s?.monitoring
  const monState = mon?.status === 'transmitting' ? 'ok' : mon?.status === 'paired_idle' ? 'warn' : 'idle'
  const busy = s?.analysis?.current

  let page
  if (route.page === 'employees' && route.param) page = <EmployeeProfile id={route.param} />
  else if (route.page === 'activity') page = <LiveFeed />
  else if (route.page === 'alerts') page = <Alerts />
  else if (route.page === 'monitoring') page = <Monitoring status={status} />
  else page = <Dashboard />
  const active = route.page === 'employees' ? 'dashboard' : route.page

  return (
    <AppContext.Provider value={ctx}>
      <div className="app">
        <aside className="sidebar">
          <div className="brand">
            <div className="brand-mark"><ShieldHalf size={18} /></div>
            <div>
              <div className="brand-name">hack<span>Viz</span></div>
              <div className="brand-sub">Insider Risk Intelligence</div>
            </div>
          </div>
          <div className="nav-label">Workspace</div>
          {NAV.map((n) => (
            <a key={n.key} href={n.to} className={`nav-item ${active === n.key ? 'active' : ''}`}>
              <n.icon size={17} />{n.label}
              {n.key === 'alerts' && alertCount.data > 0 && <span className="nav-count">{alertCount.data}</span>}
            </a>
          ))}
          <div className="nav-label">Actions</div>
          <button className="nav-item" onClick={() => setAdding(true)}><UserPlus size={17} />Add Employee</button>
          <div className="sidebar-foot">
            Assessments are investigative leads generated by a local LLM, not proof of misconduct.
            <div className="mt-8">Historical records are fictional CERT-style synthetic data.</div>
          </div>
        </aside>

        <div className="main">
          <header className="topbar">
            <h1>{TITLES[route.page] || TITLES.dashboard}</h1>
            {route.page === 'employees' && <span className="crumb mono">/ {route.param}</span>}
            <span className="spacer" />
            {busy && <Pill label={`Analyzing ${busy.employee_id}…`} state="warn pulse" title="Ollama inference in progress" />}
            <Pill label="Backend" state={!s && !status.error ? 'idle' : backendOk ? 'ok' : 'bad'} title={status.error?.message || 'FastAPI reachable'} />
            <Pill label="PostgreSQL" state={!backendOk || !s ? 'idle' : dbOk ? 'ok' : 'bad'} title={s?.database?.info} />
            <Pill label={`Ollama · ${s?.ollama?.model || 'qwen2.5:3b'}`} state={ollamaState}
              title={s?.ollama?.error || (s?.ollama?.model_available ? 'Model available' : 'Model not installed')} />
            <a href="#/monitoring" style={{ textDecoration: 'none' }}>
              <Pill label={mon?.status === 'transmitting' ? 'Extension transmitting' : mon?.status === 'paired_idle' ? 'Extension paired' : 'No extension paired'} state={monState} />
            </a>
          </header>
          <main className="content">
            {status.error && route.page !== 'monitoring' && (
              <div className="callout error mb-16">Cannot reach the hackViz backend: {status.error.message}</div>
            )}
            {page}
          </main>
        </div>
      </div>

      {eventId != null && <EventModal id={eventId} onClose={() => setEventId(null)} />}
      {adding && (
        <AddEmployeeModal
          onClose={() => setAdding(false)}
          onCreated={(emp) => {
            setAdding(false)
            setVersion((v) => v + 1)
            toast(`Employee ${emp.employee_id} — ${emp.name} created. Pair the extension with ${emp.employee_id} to start monitoring.`, 'success')
            navigate(`#/employees/${emp.employee_id}`)
          }}
        />
      )}
      {toastMsg && <div className={`toast ${toastMsg.kind}`}>{toastMsg.msg}</div>}
    </AppContext.Provider>
  )
}
